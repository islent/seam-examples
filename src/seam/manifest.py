"""Manifest I/O: TOML and JSON, losslessly convertible (SPEC 3.3)."""

from __future__ import annotations

import json
import math
import tomllib
from pathlib import Path
from typing import Any

from .model import Artifact, Manifest, Observe, Param, Provenance, SeamError

# --------------------------------------------------------------------------
# load
# --------------------------------------------------------------------------


def load(path: str | Path) -> Manifest:
    p = Path(path)
    if not p.exists():
        raise SeamError(f"manifest not found: {p}")
    raw = p.read_bytes()
    if p.suffix in (".toml", ".tml"):
        data = tomllib.loads(raw.decode("utf-8"))
    elif p.suffix == ".json":
        data = json.loads(raw.decode("utf-8"))
    else:
        raise SeamError(f"unsupported manifest extension {p.suffix!r}; use .toml or .json")
    return Manifest.from_dict(data, source_path=str(p))


def loads(text: str, fmt: str = "toml") -> Manifest:
    data = tomllib.loads(text) if fmt == "toml" else json.loads(text)
    return Manifest.from_dict(data)


# --------------------------------------------------------------------------
# save
# --------------------------------------------------------------------------


def dumps_json(m: Manifest) -> str:
    return json.dumps(m.to_dict(), indent=2, ensure_ascii=False) + "\n"


def dumps_toml(m: Manifest) -> str:
    """Emit the TOML authoring form.

    Hand-rolled rather than a dependency: the manifest grammar is small, closed, and
    known, so a general TOML writer would be more code and less control over ordering
    and comments. Order of ``[[param]]`` and ``[[observe]]`` is preserved (SPEC 3.3).
    """
    out: list[str] = []

    out.append("# Seam manifest — authoring form.")
    out.append("# Generated by `seam derive`. Comments in a hand-edited file are load-bearing:")
    out.append("# they are where the reason for a `sealed` lives.")
    out.append("")
    out.append("[seam]")
    out.append(f'version = "{m.version}"')
    if m.profile:
        out.append(f'profile = "{m.profile}"')
    out.append("")

    out.append("[identity]")
    for k, v in m.identity.items():
        out.append(f"{k} = {_val(v)}")
    out.append("")

    if m.evidence:
        out.append("[evidence]")
        for k, v in m.evidence.items():
            out.append(f"{k} = {_val(v)}")
        out.append("")

    if m.cadence:
        out.append("[cadence]")
        for k, v in m.cadence.items():
            out.append(f"{k} = {_val(v)}")
        out.append("")

    for p in m.params:
        out.append("[[param]]")
        for k, v in _ordered(p.to_dict()).items():
            out.append(f"{k} = {_inline(v)}" if k != "provenance" else f"provenance = {_inline(v)}")
        out.append("")

    for o in m.observes:
        out.append("[[observe]]")
        for k, v in _ordered(o.to_dict()).items():
            out.append(f"{k} = {_inline(v)}")
        out.append("")

    for a in m.artifacts:
        out.append("[[artifact]]")
        for k, v in _ordered(a.to_dict()).items():
            out.append(f"{k} = {_inline(v)}")
        out.append("")

    for n in m.notes:
        out.append("[[notes]]")
        for k, v in n.items():
            out.append(f"{k} = {_inline(v)}")
        out.append("")

    return "\n".join(out).rstrip() + "\n"


_ORDER = [
    "name", "affordance", "liveness", "grade", "adapter_key", "domain", "default",
    "unit", "display_scale", "transition", "timeout", "shape", "pitch", "source",
    "path", "dimensions", "doc", "provenance",
]


def _ordered(d: dict[str, Any]) -> dict[str, Any]:
    keys = [k for k in _ORDER if k in d] + [k for k in d if k not in _ORDER]
    return {k: d[k] for k in keys}


def _val(v: Any) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list):
        return "[" + ", ".join(_inline(x) for x in v) + "]"
    return json.dumps(str(v), ensure_ascii=False)


def _inline(v: Any) -> str:
    """Inline table form, used for domain and provenance."""
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k} = {_inline(x)}" for k, x in v.items()) + "}"
    if isinstance(v, list):
        return "[" + ", ".join(_inline(x) for x in v) + "]"
    if isinstance(v, float) and (math.isinf(v) or math.isnan(v)):
        raise SeamError("manifest values must be finite")
    return _val(v)


def save(m: Manifest, path: str | Path) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    text = dumps_toml(m) if p.suffix in (".toml", ".tml") else dumps_json(m)
    p.write_text(text, encoding="utf-8")
    return p


# --------------------------------------------------------------------------
# construction helpers, used by the derivation engine
# --------------------------------------------------------------------------


def param(
    name: str,
    affordance: str,
    *,
    liveness: str | None = None,
    grade: str | None = "imperative",
    domain: dict[str, Any] | None = None,
    default: Any = None,
    unit: str | None = None,
    doc: str | None = None,
    grade_of_evidence: str = "E1",
    evidence: str | None = None,
    witness: str = "unknown",
    assumed: bool = False,
    **kw: Any,
) -> Param:
    from .model import Domain

    return Param(
        name=name,
        affordance=affordance,
        liveness=liveness,
        grade=grade,
        domain=Domain(**domain) if domain else None,
        default=default,
        unit=unit,
        doc=doc,
        provenance=Provenance(grade=grade_of_evidence, witness=witness, evidence=evidence,
                              assumed=assumed),
        **kw,
    )


def observe(
    name: str,
    shape: str,
    pitch: str,
    source: str,
    *,
    unit: str | None = None,
    doc: str | None = None,
    dimensions: list[str] | None = None,
    grade_of_evidence: str = "E1",
    evidence: str | None = None,
    witness: str = "unknown",
) -> Observe:
    return Observe(
        name=name,
        shape=shape,
        pitch=pitch,
        source=source,
        unit=unit,
        doc=doc,
        dimensions=dimensions,
        provenance=Provenance(grade=grade_of_evidence, witness=witness, evidence=evidence),
    )


def artifact(
    name: str,
    path: str,
    shape: str,
    pitch: str,
    *,
    doc: str | None = None,
    witness: str = "unknown",
) -> Artifact:
    return Artifact(
        name=name, path=path, shape=shape, pitch=pitch, doc=doc,
        provenance=Provenance(grade="E1", witness=witness, evidence="source"),
    )
