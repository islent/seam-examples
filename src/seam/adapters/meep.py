"""Meep adapter — in-process Python, the one case with genuine mid-run liveness.

The plan is small and it is the whole point: Meep's step callback is Python you own, so a
control file read inside ``mp.at_every`` is a real channel, and ``liveness: perstep`` is a
claim the adapter can demonstrate rather than hope for.

Two writes are live:

* ``stop`` — sets a flag; the callback raises out of ``run()``.
* ``until`` — extends the run. Meep's documented pattern for "keep running" is to call
  ``run(until=…)`` again after it returns, so we break out and re-enter. That is a real
  mid-run change of a parameter that would otherwise be sealed.

Everything else in the manifest is ``sealed`` because the grid is built at construction.
The runtime rejects writes to those and records the rejection — it does not queue them and
pretend.
"""

from __future__ import annotations

import json
import shlex
from typing import Any

from ..adapter import Adapter, RunContext, register
from ..adapters import parse_seam_line
from ..model import Param

SCRIPT = '''#!/usr/bin/env python3
"""Generated by seam. The control file is the mid-run channel; see SPEC 4.3."""
import json, os, sys

import meep as mp
import numpy as np  # noqa: F401  (meep ships numpy; the dump uses it)

WORKDIR = __WORKDIR__
CTRL = os.path.join(WORKDIR, "seam.ctrl")
V = __VALUES__


def emit(**kw):
    print("SEAM " + json.dumps(kw, separators=(",", ":")), flush=True)


FRAME_STRIDE = 2


class Extend(Exception):
    pass


class Stop(Exception):
    pass


def read_ctrl():
    """Consume the control file. Atomic-ish: the writer appends whole lines."""
    if not os.path.exists(CTRL):
        return []
    try:
        with open(CTRL) as fh:
            lines = [ln.strip() for ln in fh if ln.strip()]
    except OSError:
        return []
    cmds = []
    for ln in lines:
        try:
            cmds.append(json.loads(ln))
        except json.JSONDecodeError:
            continue
    try:
        open(CTRL, "w").close()
    except OSError:
        pass
    return cmds


def build():
    src = [mp.Source(
        mp.GaussianSource(frequency=1.0, fwidth=0.2),
        component=mp.Ez,
        center=mp.Vector3(0, 0, 0),
    )]
    kwargs = dict(
        cell_size=mp.Vector3(V["cell_x"], V["cell_y"], 0),
        resolution=int(V["resolution"]),
        Courant=float(V["Courant"]),
        boundary_layers=[mp.PML(float(V["pml_thickness"]))],
        eps_averaging=bool(V["eps_averaging"]),
        force_complex_fields=bool(V["force_complex_fields"]),
        dimensions=int(V["dimensions"]),
        sources=src,
        progress_interval=0,
    )
    return mp.Simulation(**kwargs)


def main():
    sim = build()
    target = float(V["until"])
    ticks = 0
    state = {"stream": False}

    def tick(sim):
        nonlocal target, ticks
        ticks += 1
        for cmd in read_ctrl():
            if cmd.get("point") == "stop":
                raise Stop()
            if cmd.get("point") == "dump_slice":
                # Meep's per-component writers are attached conditionally by version and by
                # whether the component was built into the simulation, so the adapter writes the
                # array itself. An artifact is an artifact; the format is the adapter's choice.
                import numpy as _np
                _np.save(os.path.join(WORKDIR, "slice.npy"), sim.get_array(mp.Ez))
                emit(dumped="slice", **{"at": sim.meep_time()})
            if cmd.get("point") == "stream_frames":
                # A declared capability, not a hidden feature: while streaming is on, each
                # callback writes a reduced frame. What crosses the seam is a preview
                # (SPEC 4.6); the full array stays behind dump_slice.
                state["stream"] = bool(cmd.get("value", True))
            if cmd.get("point") == "until":
                new = float(cmd["value"])
                if new > target:
                    target = new
                    raise Extend()
        ez = sim.get_array(mp.Ez)
        n = float(abs(ez).max()) if ez.size else 0.0
        rms = float((abs(ez) ** 2).mean() ** 0.5) if ez.size else 0.0
        # dt = Courant / resolution is the definition in Meep's units; computing it directly
        # is more reliable than reaching for an attribute that may not be public.
        step = int(round(sim.meep_time() * float(V["resolution"]) / float(V["Courant"])))
        if state["stream"]:
            # Box-average, not stride-sample. Striding an FDTD Yee grid aliases the grid-scale
            # (Nyquist) mode into the picture and it reads as structure that is not there.
            import numpy as _np
            a = _np.abs(ez)
            h, w = (a.shape[0] // FRAME_STRIDE) * FRAME_STRIDE, (a.shape[1] // FRAME_STRIDE) * FRAME_STRIDE
            a = a[:h, :w].reshape(h // FRAME_STRIDE, FRAME_STRIDE,
                                  w // FRAME_STRIDE, FRAME_STRIDE).mean(axis=(1, 3))
            _np.save(os.path.join(WORKDIR, "frame.npy"), a)
        emit(step=step, time=sim.meep_time(), ez_max=n, ez_rms=rms)

    while True:
        try:
            sim.run(mp.at_every(1.0, tick), until=target)
            break
        except Extend:
            continue
        except Stop:
            emit(stopped=sim.meep_time())
            break
    emit(done=sim.meep_time())


if __name__ == "__main__":
    main()
'''

_DEFAULTS = {
    "cell_x": 4.0,
    "cell_y": 4.0,
    "resolution": 24,
    "Courant": 0.5,
    "pml_thickness": 1.0,
    "eps_averaging": True,
    "force_complex_fields": False,
    "dimensions": 2,
    "until": 60.0,
}

PYTHON = os.environ.get("SEAM_MEEP_PYTHON", "/opt/conda/envs/mp/bin/python")


@register
class MeepAdapter(Adapter):
    id = "meep"
    label = "Meep 1.33"
    python = PYTHON

    def render(self, ctx: RunContext) -> dict[str, str]:
        values = dict(_DEFAULTS)
        for p in ctx.manifest.params:
            if p.affordance in ("unresolved", "trigger"):
                continue
            if p.name in ctx.values and ctx.values[p.name] is not None:
                values[p.name] = ctx.values[p.name]
        script = (SCRIPT
                  .replace("__WORKDIR__", repr(ctx.workdir))
                  .replace("__VALUES__", repr(values)))
        run_sh = (
            "#!/usr/bin/env bash\n"
            "set -u\n"
            f"cd {shlex.quote(ctx.workdir)}\n"
            f"{self.python} -u run_meep.py\n"
            "echo SEAM_EXIT=$?\n"
        )
        return {"run_meep.py": script, "run.sh": run_sh}

    def run_command(self, ctx: RunContext) -> str:
        return "chmod +x run.sh && ./run.sh"

    def validate(self, ctx: RunContext) -> list[str]:
        r = ctx.transport.run(
            f"{self.python} -c 'import meep; print(meep.__version__)' 2>&1 | tail -1")
        if "1.33" not in r.out and not r.out.strip():
            return [f"meep not importable at {self.python}"]
        return []

    # -- observation ------------------------------------------------------
    def parse(self, line: str, ctx: RunContext) -> dict[str, Any]:
        payload = parse_seam_line(line)
        if not payload:
            return {}
        out: dict[str, Any] = {}
        keys = {o.name for o in ctx.manifest.observes}
        for k, v in payload.items():
            if k in keys:
                out[k] = v
        return out

    def job_time(self, state: dict[str, Any]) -> dict[str, Any] | None:
        if "time" in state:
            return {"step": state.get("step"), "t": state["time"]}
        return None

    # -- intervention -----------------------------------------------------
    def fire(self, ctx: RunContext, param: Param) -> tuple[str, str | None]:
        if param.affordance != "trigger":
            return super().fire(ctx, param)
        if param.liveness not in ("perstep", "midrun"):
            return "rejected", f"{param.name}: declared sealed, so no channel to fire on"
        ctx.append_ctrl(json.dumps({"point": param.name, "value": True}))
        return "accepted", f"written to {ctx.ctrl_file}; picked up at the next step callback"

    def set_live(self, ctx: RunContext, param: Param, value: Any) -> tuple[str, str | None]:
        if param.liveness == "perstep" or param.liveness == "midrun":
            ctx.append_ctrl(json.dumps({"point": param.name, "value": value}))
            return "accepted", f"written to {ctx.ctrl_file}; applied at the next callback"
        return "rejected", f"{param.name}: no live channel"
