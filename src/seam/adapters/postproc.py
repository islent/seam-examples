"""Post-processing adapter — a second seam over an already-finished run.

The question this answers: where does post-processing live? Two wrong answers are common.

* A menu item in the viewer. Then post-processing has parameters, but they are not declared,
  not traced, not reproducible, and invisible to the agent.
* A separate script. Then it is declared but unmanaged — no manifest, no crossings, no record
  of which numbers were used on which data.

The Seam answer: **post-processing is a run.** It has its own parameter surface, its own
observations, its own seal, its own trace. It happens to read another run's artifacts instead
of integrating a PDE, and that difference is one line of the adapter — not a new concept, and
not a new primitive.

So `manifests/postproc-gadget.toml` is a complete seam whose job is to read a Gadget-2
`energy.txt` and report the energy budget. It runs through the same seal → launch → observe →
intervene → finish loop, gets the same trace, and can be replayed as the same specimen.
"""

from __future__ import annotations

import json
import os
import shlex
from typing import Any

from ..adapter import Adapter, RunContext, register
from ..adapters import parse_seam_line
from ..model import Param

PYTHON = os.environ.get("SEAM_MEEP_PYTHON", "/opt/conda/envs/mp/bin/python")

SCRIPT = '''#!/usr/bin/env python3
"""Generated by seam: energy budget over a Gadget-2 run. Read-only, no re-integration."""
import json, math, os, sys, time

SRC = __SRC__
SKIP = __SKIP__
WIN = __WIN__
TOL = __TOL__
PACE = __PACE__


def emit(**kw):
    print("SEAM " + json.dumps(kw, separators=(",", ":")), flush=True)


path = os.path.join(SRC, "output", "energy.txt")
if not os.path.exists(path):
    print("no energy.txt at " + path, file=sys.stderr)
    raise SystemExit(3)

rows = []
with open(path) as fh:
    for line in fh:
        parts = line.split()
        if len(parts) < 4:
            continue
        try:
            rows.append(tuple(float(x) for x in parts[:4]))
        except ValueError:
            continue

if not rows:
    print("energy.txt had no parsable rows", file=sys.stderr)
    raise SystemExit(4)

rows = rows[max(0, int(SKIP)):]
if not rows:
    print("skipping %d rows consumed the whole file" % SKIP, file=sys.stderr)
    raise SystemExit(5)

e0 = rows[0][2] + rows[0][3]
window = []
drift_smoothed = 0.0
drift = 0.0
for i, (t, a, epot, ekin) in enumerate(rows):
    etot = epot + ekin
    drift = abs(etot - e0) / abs(e0) if e0 else 0.0
    virial = abs(2.0 * ekin / epot) if epot else float("nan")
    window.append(drift)
    if len(window) > max(1, int(WIN)):
        window.pop(0)
    drift_smoothed = sum(window) / len(window)
    emit(step=i, time=t, energy_pot=epot, energy_kin=ekin,
         virial_ratio=virial, energy_drift=drift, drift_smoothed=drift_smoothed)
    if PACE:
        time.sleep(PACE)

emit(drift_final=drift, within_tolerance=1.0 if drift <= TOL else 0.0, rows=len(rows))
'''

_DEFAULTS = {"skip_rows": 1, "window": 3, "tolerance": 0.05, "pace": 0.25}


@register
class PostprocAdapter(Adapter):
    id = "postproc"
    label = "post-processing (python, read-only)"

    def render(self, ctx: RunContext) -> dict[str, str]:
        src = ctx.extra.get("input")
        if not src:
            raise RuntimeError(
                "post-processing needs an input run: pass `--input <workdir of a finished run>`"
            )
        vals = dict(_DEFAULTS)
        for p in ctx.manifest.params:
            if p.name in ctx.values and ctx.values[p.name] is not None:
                vals[p.name] = ctx.values[p.name]

        script = (SCRIPT
                  .replace("__SRC__", json.dumps(src))
                  .replace("__SKIP__", repr(vals["skip_rows"]))
                  .replace("__WIN__", repr(vals["window"]))
                  .replace("__TOL__", repr(vals["tolerance"]))
                  .replace("__PACE__", repr(vals["pace"])))
        run_sh = (
            "#!/usr/bin/env bash\nset -u\n"
            f"cd {shlex.quote(ctx.workdir)}\n"
            f"{PYTHON} -u postproc.py\n"
            "echo SEAM_EXIT=$?\n"
        )
        return {"postproc.py": script, "run.sh": run_sh}

    def run_command(self, ctx: RunContext) -> str:
        return "chmod +x run.sh && ./run.sh"

    def validate(self, ctx: RunContext) -> list[str]:
        src = ctx.extra.get("input")
        if not src:
            return ["no --input given; post-processing reads another run's artifacts"]
        r = ctx.transport.run(f"test -e {shlex.quote(src)}/output/energy.txt && echo ok", timeout=30)
        if "ok" not in r.out:
            return [f"{src}/output/energy.txt not found on the target"]
        return []

    # -- observation ------------------------------------------------------
    def parse(self, line: str, ctx: RunContext) -> dict[str, Any]:
        payload = parse_seam_line(line)
        if not payload:
            return {}
        keys = {o.name for o in ctx.manifest.observes}
        return {k: v for k, v in payload.items() if k in keys}

    def job_time(self, state: dict[str, Any]) -> dict[str, Any] | None:
        if "time" in state:
            return {"step": state.get("step"), "t": state["time"]}
        return None

    # -- intervention -----------------------------------------------------
    def set_live(self, ctx: RunContext, param: Param, value: Any) -> tuple[str, str | None]:
        return "rejected", (
            "this analysis reads its inputs once at start; changing a parameter means "
            "submitting again — the same answer Meep gives for `resolution`, for the same reason"
        )
