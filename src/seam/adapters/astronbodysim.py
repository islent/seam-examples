"""AstroNbodySim.jl adapter — Julia immutable struct plus callback channels.

This is the one code where the seam already existed: ``poststep::Vector{Function}`` is
invoked after every step (``run.jl:154``), so ``perstep`` liveness is structural evidence at
E1 rather than a behavioural claim at E4. The adapter pushes a closure that reads a control
file and emits observations.

Everything in the constructor is ``sealed``, and unlike Meep that is enforced by the language:
``Simulation`` is an immutable struct, so a mid-run field assignment is not "unwise", it is
impossible. That is a better-designed surface and the manifest is correspondingly simpler.
"""

from __future__ import annotations

import json
import os
import shlex
from typing import Any

from ..adapter import Adapter, RunContext, register
from ..adapters import parse_seam_line
from ..model import Param

JULIA = os.environ.get("SEAM_JULIA", "/opt/julia/bin/julia")
PROJECT = os.environ.get("SEAM_ANS_PROJECT", "/opt/astro/AstroNbodySim.jl")
DEPOT = os.environ.get("SEAM_JULIA_DEPOT", "/opt/julia-depot")

SCRIPT = '''#!/usr/bin/env julia
# Generated by seam. poststep is the per-step channel (run.jl:154); see SPEC 4.3.
using AstroNbodySim
using AstroIC
using PhysicalParticles
using Unitful, UnitfulAstro
astro()

const WORKDIR = __WORKDIR__
const CTRL = joinpath(WORKDIR, "seam.ctrl")

struct SeamStop <: Exception end

emit(kv) = (println("SEAM {" *
    join(["\\"$(k)\\":$(v isa AbstractString ? "\\"" * v * "\\"" : repr(v))" for (k, v) in kv], ",")
    * "}"); flush(stdout))

function read_ctrl()
    isfile(CTRL) || return String[]
    lines = filter(!isempty, strip.(readlines(CTRL)))
    try; open(CTRL, "w") do io; end; catch; end
    return lines
end

mkpathIfNotExist("output")

config = PlummerStarCluster(
    collection = STAR,
    NumSamples = __NUM_SAMPLES__,
    VirialRadius = __VIRIAL_RADIUS__u"kpc",
    TotalMass = __TOTAL_MASS__u"Msun",
)
particles = generate(config, MaxRadius = __MAX_RADIUS__u"kpc")

function poststep_cb(sim)
    for line in read_ctrl()
        occursin("stop", line) && throw(SeamStop())
    end
    ti = sim.timeinfo
    emit(["step" => ti.stepcount, "time" => ustrip(ti.system_time_float),
          "scale_factor" => ti.scalefactor])
end

sim = Simulation(
    deepcopy(particles);
    TimeEnd = __TIME_END__u"Gyr",
    TimeBetweenSnapshots = __DT_SNAP__u"Gyr",
    TimeStep = __DT_STEP__u"Gyr",
    OutputDir = "output",
    poststep = Function[poststep_cb],
    Realtime = false,
)

try
    run(sim)
    emit(["status" => "finished", "step" => sim.timeinfo.stepcount,
          "time" => ustrip(sim.timeinfo.system_time_float)])
catch e
    if e isa SeamStop
        emit(["status" => "stopped", "step" => sim.timeinfo.stepcount,
              "time" => ustrip(sim.timeinfo.system_time_float)])
    else
        rethrow(e)
    end
end
'''

_DEFAULTS = {
    "num_samples": 200,
    "virial_radius": 0.01,
    "total_mass": 1.0e5,
    "max_radius": 0.1,
    "time_end": 0.01,
    "dt_snap": 0.001,
    "dt_step": 1.0e-5,
}


@register
class AstroNbodyAdapter(Adapter):
    id = "astronbodysim"
    label = "AstroNbodySim.jl"
    julia = JULIA
    project = PROJECT
    depot = DEPOT

    def render(self, ctx: RunContext) -> dict[str, str]:
        values = dict(_DEFAULTS)
        for p in ctx.manifest.params:
            if p.affordance in ("unresolved", "trigger"):
                continue
            if p.name in ctx.values and ctx.values[p.name] is not None:
                values[p.name] = ctx.values[p.name]
        script = SCRIPT.replace("__WORKDIR__", json.dumps(ctx.workdir))
        for k, v in values.items():
            script = script.replace("__" + k.upper() + "__", repr(v))
        run_sh = (
            "#!/usr/bin/env bash\n"
            "set -u\n"
            f"cd {shlex.quote(ctx.workdir)}\n"
            f"export JULIA_DEPOT_PATH={self.depot}\n"
            f"{self.julia} --project={self.project} -O2 run_ans.jl\n"
            "echo SEAM_EXIT=$?\n"
        )
        return {"run_ans.jl": script, "run.sh": run_sh}

    def run_command(self, ctx: RunContext) -> str:
        return "chmod +x run.sh && ./run.sh"

    def validate(self, ctx: RunContext) -> list[str]:
        problems = []
        r = ctx.transport.run(
            f"test -x {shlex.quote(self.julia)} && echo ok", timeout=30)
        if "ok" not in r.out:
            problems.append(f"julia not executable: {self.julia}")
        r = ctx.transport.run(
            f"export JULIA_DEPOT_PATH={self.depot}; "
            f"{self.julia} --project={self.project} -e 'using AstroNbodySim' 2>&1 | tail -3",
            timeout=180)
        if "ERROR" in r.out or "ERROR" in r.err:
            problems.append(
                "AstroNbodySim does not load: " + (r.out or r.err).strip().splitlines()[-1][:200])
        return problems

    # -- observation ------------------------------------------------------
    def parse(self, line: str, ctx: RunContext) -> dict[str, Any]:
        payload = parse_seam_line(line)
        if not payload:
            return {}
        keys = {o.name for o in ctx.manifest.observes}
        return {k: v for k, v in payload.items() if k in keys}

    def job_time(self, state: dict[str, Any]) -> dict[str, Any] | None:
        if "time" in state:
            return {"step": state.get("step"), "t": state["time"]}
        return None

    # -- intervention -----------------------------------------------------
    def fire(self, ctx: RunContext, param: Param) -> tuple[str, str | None]:
        if param.liveness not in ("perstep", "midrun"):
            return "rejected", f"{param.name}: declared sealed"
        ctx.append_ctrl(json.dumps({"point": param.name}))
        return "accepted", "closure reads the control file at the next step boundary"

    def set_live(self, ctx: RunContext, param: Param, value: Any) -> tuple[str, str | None]:
        ctx.append_ctrl(json.dumps({"point": param.name, "value": value}))
        return "accepted", "written to the per-step channel"
